country_stats = df.groupby("Country").agg(
    Sales=("Sales", "sum"), Profit=("Profit", "sum"),
    Units=("Units Sold", "sum"),
).assign(Margin=lambda x: x["Profit"] / x["Sales"]).sort_values("Profit", ascending=False)

