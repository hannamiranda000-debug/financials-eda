import pandas as pd
import numpy as np

# 1. Load the raw CSV
df = pd.read_csv('Financials.csv')
print("=" * 50)
print("STEP 1: Loaded raw file")
print("Shape:", df.shape)
print("Columns:", df.columns.tolist())
print()

# 2. Clean column names (strip extra spaces)
df.columns = df.columns.str.strip()
print("=" * 50)
print("STEP 2: Cleaned column names")
print(df.columns.tolist())
print()

# 3. Define a function to clean currency strings
def clean_currency(x):
    if pd.isna(x):
        return np.nan
    x = str(x).strip()
    # Handle accounting negatives: (123) -> -123
    if x.startswith('(') and x.endswith(')'):
        x = '-' + x[1:-1]
    # Remove $, spaces, commas
    x = x.replace('$', '').replace(' ', '').replace(',', '')
    # Bare hyphen means zero
    if x == '-' or x == '':
        return 0.0
    try:
        return float(x)
    except:
        return np.nan

# 4. Apply cleaning to all currency columns
currency_cols = [
    'Units Sold', 'Manufacturing Price', 'Sale Price',
    'Gross Sales', 'Discounts', 'Sales', 'COGS', 'Profit'
]

for col in currency_cols:
    df[col] = df[col].apply(clean_currency)

print("=" * 50)
print("STEP 3: Cleaned currency columns")
print(df[currency_cols].dtypes)
print()

# 5. Verify totals
print("=" * 50)
print("STEP 4: Totals check")
print("Total Sales:  ", df['Sales'].sum())
print("Total COGS:   ", df['COGS'].sum())
print("Total Profit: ", df['Profit'].sum())
print("Total Units:  ", df['Units Sold'].sum())
print()

# 6. Parse the Date column
df['Date'] = pd.to_datetime(df['Date'], format='%d/%m/%Y', errors='coerce')

print("=" * 50)
print("STEP 5: Parsed Date column")
print("Date range:", df['Date'].min(), "to", df['Date'].max())
print("Null dates:", df['Date'].isna().sum())
print()

# 7. Final integrity check
print("=" * 50)
print("STEP 6: Missing values per column")
print(df.isnull().sum())
print()
print("Final shape:", df.shape)
print()

# 8. Save the cleaned file
df.to_csv('financials_cleaned.csv', index=False)
print("=" * 50)
print("STEP 7: Saved cleaned file as financials_cleaned.csv")
print()

